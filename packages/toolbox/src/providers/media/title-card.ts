import { videoSpec } from '@studio/shared/ace';
import { encodeRowColorPng, type RgbColor } from '../../encoding/png-encoder';

const TOP_COLOR: RgbColor = { red: 0x0b, green: 0x14, blue: 0x26 }; // brand navy #0B1426
// The gradient lightens toward the bottom so ffmpeg blackdetect (pix_th 0.10) does not
// read a text-less frame as black: pure #0B1426 sits below that luma threshold.
const BOTTOM_COLOR: RgbColor = { red: 0x1b, green: 0x32, blue: 0x60 };
const ACCENT_COLOR: RgbColor = { red: 0x2e, green: 0xc4, blue: 0xb6 }; // brand teal #2EC4B6
const ACCENT_BAND_PX = 12;

let cachedCard: Buffer | null = null;

function mix(from: number, to: number, ratio: number): number {
  return Math.round(from + (to - from) * ratio);
}

/** 1080x1920 navy background; the Remotion template draws the scene text on top. */
export function titleCardPng(): Buffer {
  if (cachedCard) return cachedCard;
  const { width, height } = videoSpec;
  cachedCard = encodeRowColorPng({
    width,
    height,
    rowColor: (row) => {
      if (row < ACCENT_BAND_PX) return ACCENT_COLOR;
      const ratio = row / (height - 1);
      return {
        red: mix(TOP_COLOR.red, BOTTOM_COLOR.red, ratio),
        green: mix(TOP_COLOR.green, BOTTOM_COLOR.green, ratio),
        blue: mix(TOP_COLOR.blue, BOTTOM_COLOR.blue, ratio),
      };
    },
  });
  return cachedCard;
}

export const titleCardProvenance = 'title card generated by ace';
export const titleCardLicense = 'original';
